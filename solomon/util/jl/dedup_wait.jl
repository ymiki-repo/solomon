using ArgParse
function parse_cmd()
    cfg = ArgParseSettings()
    @add_arg_table cfg begin
        "--max"
        help = "maximum number of clauses in one directive, and of the wait arguments merged into one wait clause (keep it equal to the clause limit of check_clause.jl)"
        arg_type = Int
        range_tester = x -> x >= 1
        default = 32
    end
    return parse_args(cfg)
end

# every spelling of a word with lower and upper case letters (Fortran is case-insensitive)
function spellings(word::String)
    out = String[]
    n = length(word)
    for mask in 0:(2^n-1)
        s = [((mask >> (ii - 1)) & 1) == 1 ? uppercase(c) : c for (ii, c) in enumerate(word)]
        push!(out, String(s))
    end
    return out
end

function generate(io::IO, N_max::Int)
    P = "SOLOMON_INTERNAL_DEDUP_"
    # the list holds up to N_max clauses and the mark of the clause limit (check_clause.jl), then the empty last element
    N_gen = N_max + 1
    println(io, "///")
    println(io, "/// @file solomon/util/impl/dedup_wait.hpp")
    println(io, "/// @brief Auto-generated macros for SOLOMON_INTERNAL_DEDUP_WAIT (solomon/util/dedup_wait.hpp) up to $N_max clauses")
    println(io, "/// @note Generated by dedup_wait.jl with --max $N_max")
    println(io, "/// @note DO NOT EDIT THIS FILE MANUALLY - Regenerate with:")
    println(io, "///       cd solomon/util && julia jl/dedup_wait.jl --max $N_max")
    println(io, "///")
    println(io)
    println(io, "#if !defined(SOLOMON_UTIL_IMPL_DEDUP_WAIT_HPP)")
    println(io, "#define SOLOMON_UTIL_IMPL_DEDUP_WAIT_HPP")

    # modifiers of the wait argument (devnum: / queues:) in every spelling
    println(io)
    println(io, "///")
    println(io, "/// @brief modifiers of the wait argument (devnum: / queues:), every spelling")
    println(io, "///")
    for s in spellings("devnum")
        println(io, "#define $(P)MOD_$s SOLOMON_INTERNAL_CLOAK_PROBE(~)")
    end
    for s in spellings("queues")
        println(io, "#define $(P)MQ_$s SOLOMON_INTERNAL_CLOAK_PROBE(~)")
    end

    # MULTI_n(s, c1, ...): 1 when the segment (up to the next device_type) holds two or more wait clauses
    println(io)
    println(io, "///")
    println(io, "/// @brief 1 when the segment (up to the next device_type) holds two or more wait clauses")
    println(io, "///")
    println(io, "#define $(P)MULTI_0(s) 0")
    println(io, "#define $(P)MULTI_1(s, c1) $(P)IIF_E($(P)IS_DT(c1))(0, $(P)AND(s, $(P)IS_WAIT(c1)))")
    for n in 2:N_gen
        println(io, "#define $(P)MULTI_$n(s, c1, ...) $(P)IIF_E($(P)IS_DT(c1))(0, $(P)IIF_F($(P)AND(s, $(P)IS_WAIT(c1)))(1, $(P)MULTI_$(n-1)($(P)OR(s, $(P)IS_WAIT(c1)), __VA_ARGS__)))")
    end

    # ANYB_n(c1, ...): 1 when the segment holds a wait without arguments
    println(io)
    println(io, "///")
    println(io, "/// @brief 1 when the segment holds a wait clause without arguments (wait or wait())")
    println(io, "///")
    println(io, "#define $(P)ANYB_0() 0")
    println(io, "#define $(P)ANYB_1(c1) $(P)IIF_E($(P)IS_DT(c1))(0, $(P)IS_BARE(c1))")
    for n in 2:N_gen
        println(io, "#define $(P)ANYB_$n(c1, ...) $(P)IIF_E($(P)IS_DT(c1))(0, $(P)OR($(P)IS_BARE(c1), $(P)ANYB_$(n-1)(__VA_ARGS__)))")
    end

    # ALLP_n(c1, ...): the arguments of the wait clauses without modifier in the segment, each followed by a comma
    println(io)
    println(io, "///")
    println(io, "/// @brief the arguments of the wait clauses without modifier in the segment, each followed by a comma")
    println(io, "///")
    println(io, "#define $(P)ALLP_0()")
    println(io, "#define $(P)ALLP_1(c1) $(P)IIF_E($(P)IS_DT(c1))(, $(P)PARGS(c1))")
    for n in 2:N_gen
        println(io, "#define $(P)ALLP_$n(c1, ...) $(P)IIF_E($(P)IS_DT(c1))(, $(P)PARGS(c1) $(P)ALLP_$(n-1)(__VA_ARGS__))")
    end

    # DROPLAST_n(a1, ..., an): drop the last element and keep the commas between the others
    println(io)
    println(io, "///")
    println(io, "/// @brief drop the last element of a list (the empty element after the trailing comma)")
    println(io, "///")
    println(io, "#define $(P)DROPLAST_0()")
    println(io, "#define $(P)DROPLAST_1(a1)")
    for n in 2:(N_gen+1)
        args = join(["a$ii" for ii in 1:n], ", ")
        keep = join(["a$ii" for ii in 1:(n-1)], ", ")
        println(io, "#define $(P)DROPLAST_$n($args) $keep")
    end

    # EMIT_n(seen, S, c1, ...): emit the clauses; the segment state S is recomputed after each device_type
    println(io)
    println(io, "///")
    println(io, "/// @brief emit the clauses; the segment state is recomputed after each device_type")
    println(io, "/// @note each level has its own helper names (a helper called again from a deeper level would not expand)")
    println(io, "///")
    println(io, "#define $(P)EMIT_0(seen, S, ...)")
    println(io, "#define $(P)EMIT_1(seen, S, c1) $(P)ONE(seen, S, c1)")
    for n in 2:N_gen
        println(io, "#define $(P)NEXT_DT_$n(seen, S, c1, ...) $(P)ONE(seen, S, c1) $(P)EMIT_$(n-1)(0, $(P)STATE($(n-1), __VA_ARGS__), __VA_ARGS__)")
        println(io, "#define $(P)NEXT_NO_$n(seen, S, c1, ...) $(P)ONE(seen, S, c1) $(P)EMIT_$(n-1)($(P)SEEN(seen, S, c1), S, __VA_ARGS__)")
        println(io, "#define $(P)EMIT_$n(seen, S, c1, ...) $(P)IIF_R($(P)IS_DT(c1))($(P)NEXT_DT_$n, $(P)NEXT_NO_$n)(seen, S, c1, __VA_ARGS__)")
    end

    # FITS_k: k elements (the merged wait arguments and the empty last one) fit in one wait clause
    println(io)
    println(io, "///")
    println(io, "/// @brief the limit of the wait arguments merged into one wait clause, and the list lengths within it")
    println(io, "///")
    println(io, "#define $(P)ARGS_MAX $N_max")
    for k in 0:(N_max+1)
        println(io, "#define $(P)FITS_$k SOLOMON_INTERNAL_CLOAK_PROBE(~)")
    end

    println(io)
    println(io, "///")
    println(io, "/// @note SOLOMON_INTERNAL_DEDUP_WAIT handles up to $N_max clauses and the mark of the clause limit (a list of $(N_gen + 1) elements with the empty last one);")
    println(io, "///       more than $N_max merged wait arguments stop the build")
    println(io, "///       If you need more:")
    println(io, "///       - Run: cd solomon/util && julia jl/dedup_wait.jl --max N")
    println(io, "///")
    println(io)
    println(io, "#endif // !defined(SOLOMON_UTIL_IMPL_DEDUP_WAIT_HPP)")
end

function main()
    argv = parse_cmd()
    N_max = argv["max"]

    output = joinpath(@__DIR__, "..", "impl", "dedup_wait.hpp")
    output_dir = dirname(output)
    if !isdir(output_dir)
        mkpath(output_dir)
    end

    open(output, "w") do io
        generate(io, N_max)
    end
end

main()
