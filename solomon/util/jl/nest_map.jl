using ArgParse
function parse_cmd()
    cfg = ArgParseSettings()
    @add_arg_table cfg begin
        "--max"
        help = "maximum number of nested clauses in one OMP_TARGET_CLAUSE_MAP (keep it equal to the clause limit of check_clause.jl)"
        arg_type = Int
        range_tester = x -> x >= 1
        default = 32
        "--mods"
        help = "maximum number of Solomon map modifiers (OMP_TARGET_MAP_MODIFIER_*) in front of the nested clauses"
        arg_type = Int
        range_tester = x -> x >= 0
        default = 6
    end
    return parse_args(cfg)
end

function generate(io::IO, N_max::Int, M_max::Int)
    P = "SOLOMON_INTERNAL_NEST_"
    println(io, "///")
    println(io, "/// @file solomon/util/impl/nest_map.hpp")
    println(io, "/// @brief Auto-generated stages for SOLOMON_INTERNAL_NEST_MAP (solomon/util/nest_map.hpp) up to $N_max nested clauses and $M_max modifiers")
    println(io, "/// @note Generated by nest_map.jl with --max $N_max --mods $M_max")
    println(io, "/// @note DO NOT EDIT THIS FILE MANUALLY - Regenerate with:")
    println(io, "///       cd solomon/util && julia jl/nest_map.jl --max $N_max --mods $M_max")
    println(io, "///")
    println(io)
    println(io, "#if !defined(SOLOMON_UTIL_IMPL_NEST_MAP_HPP)")
    println(io, "#define SOLOMON_UTIL_IMPL_NEST_MAP_HPP")
    # the limit of nested clauses, compared with the clause limit of check_clause.jl (solomon/util/pickup.hpp, solomon/util/nest_map.hpp)
    println(io)
    println(io, "#define $(P)MAX $N_max")

    # MODS_k(pfx, raw, mods, ...): collect one more Solomon modifier, or go to the first nested clause;
    # a modifier is two elements: the mark that stops it outside the map (dropped here), then its payload
    println(io)
    println(io, "///")
    println(io, "/// @brief collect the Solomon modifiers in front of the nested clauses (up to $M_max; one more stops the map)")
    println(io, "///")
    println(io, "#define $(P)MODS_MAX $M_max")
    for k in 1:M_max
        println(io, "#define $(P)MODS_$k(pfx, raw, mods, ...) SOLOMON_INTERNAL_CLOAK_IIF($(P)IS_MOD(__VA_ARGS__))($(P)MODADD_$k, $(P)FIRST)(pfx, raw, mods, __VA_ARGS__)")
        println(io, "#define $(P)MODADD_$k(pfx, raw, mods, c, n, ...) $(P)MODTAKE_$k(pfx, raw, mods, SOLOMON_INTERNAL_RETRIEVE_ARGS(n, __VA_ARGS__))")
        println(io, "#define $(P)MODTAKE_$k(pfx, raw, mods, ...) $(P)MODTAKE_$(k)_(pfx, raw, mods, __VA_ARGS__)")
        println(io, "#define $(P)MODTAKE_$(k)_(pfx, raw, mods, c, n, ...) $(P)MODS_$(k+1)(pfx, raw, SOLOMON_INTERNAL_CLOAK_CAT(pfx, MODADD)(mods, SOLOMON_INTERNAL_CLOAK_CAT(pfx, c)), SOLOMON_INTERNAL_RETRIEVE_ARGS(n, __VA_ARGS__))")
    end
    println(io, "#define $(P)MODS_$(M_max+1)(pfx, raw, mods, ...) SOLOMON_INTERNAL_CLOAK_IIF($(P)IS_MOD(__VA_ARGS__))($(P)TOOMANY, $(P)FIRST)(pfx, raw, mods, __VA_ARGS__)")

    # STEP_k / NEXT_k / MORE_k: rewrite the k-th nested clause, then stop at the end mark or go on with the next one
    println(io)
    println(io, "///")
    println(io, "/// @brief rewrite the nested clauses one by one (up to $N_max); an element that is not a nested clause stops the map")
    println(io, "///")
    for k in 1:N_max
        println(io, "#define $(P)STEP_$k(pfx, raw, mods, c, n, ...) $(P)ONE(pfx, mods, c, $(P)E1_X(__VA_ARGS__, ~)) $(P)NEXT_$k(pfx, raw, mods, SOLOMON_INTERNAL_RETRIEVE_ARGS(n, __VA_ARGS__))")
        println(io, "#define $(P)NEXT_$k(pfx, raw, mods, ...) SOLOMON_INTERNAL_CLOAK_IIF($(P)IS_END(__VA_ARGS__))($(P)EAT, $(P)MORE_$k)(pfx, raw, mods, __VA_ARGS__)")
        println(io, "#define $(P)MORE_$k(pfx, raw, mods, ...) , SOLOMON_INTERNAL_CLOAK_IIF($(P)IS_NESTED(__VA_ARGS__))($(P)STEP_$(k+1), $(P)MIXED)(pfx, raw, mods, __VA_ARGS__)")
    end
    # SCAN_k(d, e, ...): probe the k-th element after the third one of a raw list (RAWCHK in solomon/util/nest_map.hpp);
    # 1 when a flag of a nested clause or of a modifier comes before the end mark, 0 at the end mark or after $N_max elements
    println(io)
    println(io, "///")
    println(io, "/// @brief scan a raw list from its fourth element (up to $N_max elements): 1 when a nested clause or a modifier follows it")
    println(io, "///")
    for k in 1:N_max
        println(io, "#define $(P)SCAN_$k(d, e, ...) SOLOMON_INTERNAL_CLOAK_IIF($(P)IS_ANY(e))($(P)SCAN_HIT, $(P)SCAN_$(k+1))(e, __VA_ARGS__)")
    end
    println(io, "#define $(P)SCAN_$(N_max+1)(...) 0")

    println(io)
    println(io, "///")
    println(io, "/// @warning More than $N_max nested clauses in one OMP_TARGET_CLAUSE_MAP leave $(P)STEP_$(N_max+1) unexpanded (the compiler stops);")
    println(io, "///          the clause limit of one directive (check_clause.jl --max) stops such a directive first.")
    println(io, "///          To raise them, regenerate check_clause.jl, sort_clause.jl, dedup_wait.jl, and nest_map.jl with the same --max (README)")
    println(io, "///")
    println(io)
    println(io, "#endif // !defined(SOLOMON_UTIL_IMPL_NEST_MAP_HPP)")
end

function main()
    argv = parse_cmd()
    N_max = argv["max"]
    M_max = argv["mods"]

    output = joinpath(@__DIR__, "..", "impl", "nest_map.hpp")
    output_dir = dirname(output)
    if !isdir(output_dir)
        mkpath(output_dir)
    end

    open(output, "w") do io
        generate(io, N_max, M_max)
    end
end

main()
