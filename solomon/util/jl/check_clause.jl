using ArgParse
function parse_cmd()
    cfg = ArgParseSettings()
    @add_arg_table cfg begin
        "--max"
        help = "maximum number"
        arg_type = Int
        range_tester = x -> x >= 1
        default = 32
    end
    return parse_args(cfg)
end

function generate(io::IO, N_max::Int)
    # Header with update instructions
    println(io, "///")
    println(io, "/// @file solomon/util/impl/check_clause.hpp")
    println(io, "/// @brief Auto-generated macros for SOLOMON_INTERNAL_CHECK_CLAUSE macros up to $N_max inputs")
    println(io, "/// @note Generated by check_clause.jl with --max $N_max")
    println(io, "/// @note DO NOT EDIT THIS FILE MANUALLY - Regenerate with:")
    println(io, "///       cd solomon/util && julia jl/check_clause.jl --max $N_max")
    println(io, "///")
    println(io)
    println(io, "#if !defined(SOLOMON_UTIL_IMPL_CHECK_CLAUSE_HPP)")
    println(io, "#define SOLOMON_UTIL_IMPL_CHECK_CLAUSE_HPP")

    # the clause limit, for the message of the overflow mark (solomon/util/pickup.hpp)
    println(io)
    println(io, "#define SOLOMON_INTERNAL_CHECK_CLAUSE_MAX ", N_max)

    # generate SOLOMON_INTERNAL_PICKUP_DRAIN_N(...): drop up to N_max leading empty elements of the clause list
    println(io)
    println(io, "#define SOLOMON_INTERNAL_PICKUP_DRAIN(...) SOLOMON_INTERNAL_PICKUP_DRAIN_", N_max, "(__VA_ARGS__)")
    println(io, "#define SOLOMON_INTERNAL_PICKUP_DRAIN_0(...) __VA_ARGS__")
    for ii in 1:N_max
        println(io, "#define SOLOMON_INTERNAL_PICKUP_DRAIN_", ii, "(...) SOLOMON_INTERNAL_CLOAK_IIF(SOLOMON_INTERNAL_PICKUP_LEAD_EMPTY(__VA_ARGS__))(SOLOMON_INTERNAL_PICKUP_DRAIN_STEP_", ii, ", SOLOMON_INTERNAL_PICKUP_ID)(__VA_ARGS__)")
        println(io, "#define SOLOMON_INTERNAL_PICKUP_DRAIN_STEP_", ii, "(...) SOLOMON_INTERNAL_PICKUP_DRAIN_", ii - 1, "(SOLOMON_INTERNAL_PICKUP_SKIP_ONE(__VA_ARGS__))")
    end

    # generate SOLOMON_INTERNAL_CHECK_CLAUSE_N(...): one candidate per stage; the chain stops when the list is exhausted,
    # and the stage 0 marks the candidates left over after N_max stages (solomon/util/pickup.hpp)
    println(io)
    println(io, "#define SOLOMON_INTERNAL_CHECK_CLAUSE_0(...) SOLOMON_INTERNAL_CHECK_CLAUSE_OVERFLOW(SOLOMON_INTERNAL_PICKUP_CLAUSE_ARGS(__VA_ARGS__))")
    for ii in 1:N_max
        println(io, "#define SOLOMON_INTERNAL_CHECK_CLAUSE_", ii, "(...) SOLOMON_INTERNAL_CLOAK_IIF(SOLOMON_INTERNAL_PICKUP_IS_EXHAUSTED(SOLOMON_INTERNAL_PICKUP_CLAUSE_ARGS(__VA_ARGS__)))(SOLOMON_INTERNAL_CLOAK_EAT, SOLOMON_INTERNAL_CHECK_CLAUSE_BODY_", ii, ")(__VA_ARGS__)")
        println(io, "#define SOLOMON_INTERNAL_CHECK_CLAUSE_BODY_", ii, "(...) SOLOMON_INTERNAL_CHECK_CLAUSE(__VA_ARGS__) SOLOMON_INTERNAL_CHECK_CLAUSE_", ii - 1, "(SOLOMON_INTERNAL_ARGS_WITH_NUM(SOLOMON_INTERNAL_PICKUP_DIRECTIVE_TAGS(__VA_ARGS__)) SOLOMON_APPEND_ARGS(SOLOMON_INTERNAL_PICKUP_RETRIEVE_CLAUSE_CANDIDATE(SOLOMON_INTERNAL_PICKUP_CLAUSE_ARGS(__VA_ARGS__))))")
    end

    # New SOLOMON_INTERNAL_APPEND_CLAUSES with automatic clause sorting
    println(io)
    println(io, "///")
    println(io, "/// @brief Apply automatic clause sorting after checking valid clauses")
    println(io, "/// @note This moves the clauses of priority level 1 (simd; solomon/util/sort.hpp) to the front")
    println(io, "/// @warning More than ", N_max, " clause candidates (empty elements are not counted) stop the build:")
    println(io, "///          - Error message: 'Solomon: too many clauses for one directive (limit ", N_max, ")'")
    println(io, "///          - To raise the limit, regenerate check_clause.jl, sort_clause.jl, dedup_wait.jl, and nest_map.jl with the same --max (README)")
    println(io, "///")
    println(io, "#define SOLOMON_INTERNAL_APPEND_CLAUSES(...) SOLOMON_INTERNAL_SORT_AND_OUTPUT(SOLOMON_INTERNAL_CHECK_CLAUSE_", N_max, "(SOLOMON_INTERNAL_PICKUP_DRAIN_ENTRY(__VA_ARGS__)))")

    # generate SOLOMON_INTERNAL_PARENS_FIRST_N(...): the checked list (up to N_max clauses, the mark of the clause limit,
    # and the empty last element) without its commas, the parenthesized elements first and the others after them,
    # each group in the given order
    N_generate = N_max + 2
    println(io)
    println(io, "#define SOLOMON_INTERNAL_PARENS_ONLY(x) SOLOMON_INTERNAL_CLOAK_IIF(SOLOMON_INTERNAL_CLOAK_IS_PAREN(x))(SOLOMON_INTERNAL_PICKUP_ID, SOLOMON_INTERNAL_CLOAK_EAT)(x)")
    println(io, "#define SOLOMON_INTERNAL_PARENS_OTHER(x) SOLOMON_INTERNAL_CLOAK_IIF(SOLOMON_INTERNAL_CLOAK_IS_PAREN(x))(SOLOMON_INTERNAL_CLOAK_EAT, SOLOMON_INTERNAL_PICKUP_ID)(x)")
    println(io, "#define SOLOMON_INTERNAL_PARENS_FIRST(...) SOLOMON_INTERNAL_CLOAK_CAT(SOLOMON_INTERNAL_PARENS_FIRST_, SOLOMON_INTERNAL_NUM_ARGS(__VA_ARGS__))(__VA_ARGS__)")
    println(io, "#define SOLOMON_INTERNAL_PARENS_FIRST_0()")
    for ii in 1:N_generate
        args = join(["a$jj" for jj in 1:ii], ", ")
        front = join(["SOLOMON_INTERNAL_PARENS_ONLY(a$jj)" for jj in 1:ii], " ")
        back = join(["SOLOMON_INTERNAL_PARENS_OTHER(a$jj)" for jj in 1:ii], " ")
        println(io, "#define SOLOMON_INTERNAL_PARENS_FIRST_", ii, "(", args, ") ", front, " ", back)
    end

    # SOLOMON_INTERNAL_APPEND_CLAUSES_WITHOUT_SORTING: checking only, without clause sorting
    println(io)
    println(io, "///")
    println(io, "/// @brief Apply automatic checking valid clauses")
    println(io, "/// @note Required for directives whose clauses may be parenthesized lists (e.g., routine(name), declare target(list)); the sorting stage token-pastes clause texts and cannot handle them")
    println(io, "/// @note The parenthesized elements come first (e.g., routine (name) seq, as OpenACC requires the name right after routine)")
    println(io, "/// @warning More than ", N_max, " clause candidates (empty elements are not counted) stop the build:")
    println(io, "///          - Error message: 'Solomon: too many clauses for one directive (limit ", N_max, ")'")
    println(io, "///          - To raise the limit, regenerate check_clause.jl, sort_clause.jl, dedup_wait.jl, and nest_map.jl with the same --max (README)")
    println(io, "///")
    println(io, "#define SOLOMON_INTERNAL_APPEND_CLAUSES_WITHOUT_SORTING(...) SOLOMON_INTERNAL_PARENS_FIRST(SOLOMON_INTERNAL_CHECK_CLAUSE_", N_max, "(SOLOMON_INTERNAL_PICKUP_DRAIN_ENTRY(__VA_ARGS__)))")

    println(io)
    println(io, "#endif  // !defined(SOLOMON_UTIL_IMPL_CHECK_CLAUSE_HPP)")
end

function main()
    # read options
    argv = parse_cmd()
    N_max = argv["max"]

    output = joinpath(dirname(realpath(@__FILE__)), "..", "impl", "check_clause.hpp")
    output_dir = dirname(output)
    if !isdir(output_dir)
        mkpath(output_dir)
    end

    open(output, "w") do io
        generate(io, N_max)
    end
end

main()
