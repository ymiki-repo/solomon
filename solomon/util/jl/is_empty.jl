using ArgParse
function parse_cmd()
    cfg = ArgParseSettings()
    @add_arg_table cfg begin
        "--max"
        help = "maximum number of commas detected by SOLOMON_INTERNAL_HAS_COMMA"
        arg_type = Int
        range_tester = x -> x >= 1
        default = 32
    end
    return parse_args(cfg)
end

function generate(io::IO, N_max::Int)
    println(io, "///")
    println(io, "/// @file solomon/util/impl/is_empty.hpp")
    println(io, "/// @brief Auto-generated comma detection for SOLOMON_INTERNAL_IS_EMPTY and SOLOMON_INTERNAL_HAS_EMPTY_ELEMENT (solomon/util/is_empty.hpp) up to $N_max commas")
    println(io, "/// @note Generated by is_empty.jl with --max $N_max")
    println(io, "/// @note DO NOT EDIT THIS FILE MANUALLY - Regenerate with:")
    println(io, "///       cd solomon/util && julia jl/is_empty.jl --max $N_max")
    println(io, "///")
    println(io)
    println(io, "#if !defined(SOLOMON_UTIL_IMPL_IS_EMPTY_HPP)")
    println(io, "#define SOLOMON_UTIL_IMPL_IS_EMPTY_HPP")
    println(io)

    # SOLOMON_INTERNAL_IE_ARGN(_1, ..., _{N+2}, ...) _{N+2}
    println(io, "///")
    println(io, "/// @brief pick the (N + 2)-th argument")
    println(io, "///")
    print(io, "#define SOLOMON_INTERNAL_IE_ARGN(")
    for ii in 1:(N_max+2)
        print(io, "_", ii, ", ")
    end
    println(io, "...) _", N_max + 2)
    println(io)

    # SOLOMON_INTERNAL_HAS_COMMA(...): 1 when the arguments contain a top-level comma (up to N_max commas), 0 otherwise
    println(io, "///")
    println(io, "/// @brief 1 when the arguments contain a top-level comma (up to $N_max commas), 0 otherwise")
    println(io, "///")
    print(io, "#define SOLOMON_INTERNAL_HAS_COMMA(...) SOLOMON_INTERNAL_IE_ARGN(__VA_ARGS__")
    for ii in 1:N_max
        print(io, ", 1")
    end
    println(io, ", 0, ~)")
    println(io)

    # SOLOMON_INTERNAL_IE_ANY_k(e1, ..., ek): 1 when one of the k elements is empty (k up to N_max + 1, the elements that
    # SOLOMON_INTERNAL_HAS_COMMA can separate); SOLOMON_INTERNAL_IE_FITS_k probes that k is within the limit
    println(io, "///")
    println(io, "/// @brief 1 when one of the k elements is empty, 0 otherwise (k up to $(N_max + 1); SOLOMON_INTERNAL_HAS_EMPTY_ELEMENT in is_empty.hpp)")
    println(io, "///")
    for k in 1:(N_max+1)
        println(io, "#define SOLOMON_INTERNAL_IE_FITS_$k SOLOMON_INTERNAL_CLOAK_PROBE(~)")
    end
    println(io, "#define SOLOMON_INTERNAL_IE_ANY_1(e) SOLOMON_INTERNAL_IS_EMPTY(e)")
    for k in 2:(N_max+1)
        println(io, "#define SOLOMON_INTERNAL_IE_ANY_$k(e, ...) SOLOMON_INTERNAL_CLOAK_BITOR(SOLOMON_INTERNAL_IS_EMPTY(e))(SOLOMON_INTERNAL_IE_ANY_$(k-1)(__VA_ARGS__))")
    end
    println(io)
    println(io, "#endif // !defined(SOLOMON_UTIL_IMPL_IS_EMPTY_HPP)")
end

function main()
    argv = parse_cmd()
    N_max = argv["max"]

    output = joinpath(@__DIR__, "..", "impl", "is_empty.hpp")
    output_dir = dirname(output)
    if !isdir(output_dir)
        mkpath(output_dir)
    end

    open(output, "w") do io
        generate(io, N_max)
    end
end

main()
