///
/// @file solomon/util/dedup_wait.hpp
/// @author Yohei MIKI (The University of Tokyo)
/// @brief merge the wait clauses of one directive (OpenACC 3.3, 2.4 and 2.16)
/// @details SOLOMON_INTERNAL_DEDUP_WAIT(...) takes the selected clauses of one directive (a list ending with an empty
/// element) and returns the same list with the wait clauses merged. The list is cut into segments at the head and
/// after each device_type(...) (device_type itself stays where it is); in each segment:
///   - a segment with one wait clause or none is kept, except that an empty wait() becomes wait;
///   - with two or more wait clauses and a wait without arguments (wait or wait()), the waits for the current device
///     (without arguments, a plain list, or queues:) become one wait at the place of the first of them; waits with
///     devnum: are kept;
///   - with two or more wait clauses and no wait without arguments, the plain lists are merged into one
///     wait(..., ...) at the place of the first of them; waits with queues: or devnum: are kept;
///   - the other clauses keep their order.
/// In a segment with two or more wait clauses, the first token of each wait argument is pasted to detect devnum: and
/// queues: (in every spelling); it must be a name, an integer or a parenthesis (write wait((*p)) instead of wait(*p)).
/// A variable named devnum or queues as the first token is taken as the modifier and kept unmerged.
/// Up to SOLOMON_INTERNAL_DEDUP_ARGS_MAX (impl/dedup_wait.hpp) arguments are merged into one wait clause; more stop the
/// build with a Solomon error.
///
/// @copyright Copyright (c) 2026 Yohei MIKI
///
